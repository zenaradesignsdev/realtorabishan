/**
 * Regenerates src/lib/image-blur.ts — the low-quality placeholders (LQIP) that
 * <Image /> uses while a photo decodes.
 *
 * next/image produces these automatically for statically imported images, but
 * this project references photos by their public path, so they are precomputed
 * here instead. Run after adding, replacing, or re-cropping anything in
 * public/images:
 *
 *   node scripts/generate-image-blur.mjs
 *
 * sharp is already present as a Next.js image-optimisation dependency.
 */
import sharp from 'sharp'
import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const DIR = 'public/images'
// The brokerage mark is line art on a transparent ground — a blurred version
// reads as a grey smudge behind it, which is worse than the empty box.
const SKIP = new Set(['royal-lepage-ignite.png'])

const files = readdirSync(DIR)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f) && !SKIP.has(f))
  .sort()

const entries = []
for (const file of files) {
  const buf = await sharp(path.join(DIR, file))
    .resize(12, 12, { fit: 'inside' })
    .webp({ quality: 35 })
    .toBuffer()
  entries.push([`/images/${file}`, `data:image/webp;base64,${buf.toString('base64')}`])
  console.log(`${file} -> ${buf.length}B`)
}

const body = entries.map(([k, v]) => `  '${k}':\n    '${v}',`).join('\n')

writeFileSync(
  'src/lib/image-blur.ts',
  `// Generated by scripts/generate-image-blur.mjs — do not edit by hand.
/**
 * Low-quality image placeholders, keyed by the same \`src\` path passed to
 * <Image />. Each is a 12px-wide WebP inlined as a data URI (a few hundred
 * bytes). Without one, a photo on a cream or white section paints as an empty
 * rectangle until it decodes.
 */
export const IMAGE_BLUR: Readonly<Record<string, string>> = {
${body}
}

/** The placeholder for a src, or undefined if none was generated. */
export function blurFor(src: string): string | undefined {
  return IMAGE_BLUR[src]
}
`
)
console.log(`\nwrote src/lib/image-blur.ts (${entries.length} entries)`)
